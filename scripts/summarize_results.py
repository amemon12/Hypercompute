"""Render docs/RESULTS.md from the raw evidence JSON in results/ (never hand-edit the numbers).

  uv run python scripts/summarize_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(v: float | None, digits: int = 1) -> str:
    return "n/a" if v is None else f"{v:.{digits}f}"


def stat(s: dict | None, digits: int = 1) -> str:
    if not s or s.get("median") is None:
        return "n/a"
    return f"{fmt(s['median'], digits)} [{fmt(s['min'], digits)}-{fmt(s['max'], digits)}]"



def _device(d: dict) -> str:
    """'CUDA0 44L/10087MiB'; engines that place layers themselves (vLLM, AirLLM, EXO) report no layer count."""
    layers = f"{d['layers_est']}L/" if d.get("layers_est") is not None else ""
    return f"{d['name']} {layers}{d['model_bytes'] / 2**20:.0f}MiB"


def _concurrency_section() -> list[str]:
    """Many users at once, from results/concurrency-*.jsonl (one line per engine label and concurrency level)."""
    rows = []
    for path in sorted((ROOT / "results").glob("concurrency-*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            decode = r["per_request_decode_tps_median"]
            rows.append(f"| `{path.name}` | {r['label']} | {r['model']} | {r['concurrency']} | "
                        f"{r['ok']}/{r['requests']} | {r['aggregate_tps']:.1f} | {decode:.1f} | "
                        f"{r['ttft_ms_median']:.0f} / {r['ttft_ms_p90']:.0f} |")
    if not rows:
        return []
    return ["## Many users at once (concurrency)", "",
            "Each level sends 32 streamed requests of 128 tokens (`ignore_eos`, unique prompts) through one client. "
            "`direct` labels talk to the engine itself; `gateway-` labels go through Hypercompute's own "
            "`/v1/chat/completions` with per-engine inference slots.", "",
            "| evidence | label | model | users at once | ok | total tok/s | per-request decode tok/s | "
            "TTFT ms p50 / p90 |",
            "|---|---|---|---|---|---|---|---|", *rows, ""]

def main() -> None:
    rows, bench_rows, lifecycle_rows = [], [], []
    lifecycle_files = sorted((ROOT / "results").glob("lifecycle-*.json"))
    if lifecycle_files:
        latest = json.loads(lifecycle_files[-1].read_text(encoding="utf-8"))
        for d in latest["deployments"]:
            if d["final_state"] == "failed":
                lifecycle_rows.append(f"| `{d['id'][:8]}` | {d['model']} | {' + '.join(d['devices'])} | "
                                      f"{d['error']} | {d['cleanup']} |")
    for path in sorted((ROOT / "results").glob("*.json")):
        if path.name.startswith("lifecycle-"):
            continue
        e = json.loads(path.read_text(encoding="utf-8"))
        dep = e.get("deployment") or {}
        plan = e.get("plan") or {}
        placement = dep.get("placement") or {}
        devices = [d for d in placement.get("devices", []) if d["model_bytes"] and
                   not d["name"].startswith(("CPU", "CUDA_Host"))]
        layout = " + ".join(_device(d) for d in devices)
        if plan.get("cpu_layers"):  # the host CPU tier (llama.cpp's CPU_Mapped buffer is filtered out above)
            layout = f"CPU {plan['cpu_layers']}L + {layout}"
        if layout and plan.get("engine", "llama_rpc") != "llama_rpc":
            layout = f"{plan['engine']}: {layout}"
        model = plan.get("model_id") or (e.get("args") or {}).get("model", "?")  # the selector may swap the model
        peers = ", ".join(n["display_name"] for n in e.get("nodes", []) if not n.get("is_local")
                          and any(a["node_id"] == n["id"] for a in plan.get("assignments", [])))
        rows.append(f"| `{path.name}` | {model} | {plan.get('strategy', '?')} | {dep.get('state', 'refused')} | "
                    f"{layout or 'n/a'} | {peers or 'none'} | {fmt(e.get('load_seconds'))} | "
                    f"{'yes' if dep.get('participation_verified') else 'no'} |")
        bench = e.get("benchmark") or {}
        bench_runs = [r for r in e.get("runs", []) if r.get("benchmark_id") == bench.get("id")]
        cache_off = bench_runs and all(r["sampling"].get("cache_prompt") is False for r in bench_runs)
        cache = "off" if cache_off else "ON (prefix reuse: long-prompt TTFT understated)"
        for s in bench.get("summaries", []):
            bench_rows.append(f"| `{path.name}` | {model} | {s['prompt_label']} | {cache} | {stat(s['ttft_ms'], 0)} | "
                              f"{stat(s['decode_tokens_per_s'])} | {stat(s['prompt_tokens_per_s'], 0)} | "
                              f"{s['ttft_ms']['n']} | {s['failures']} |")
    out = [
        "# Measured results",
        "",
        "Generated by `scripts/summarize_results.py` from the raw evidence in `results/*.json`.",
        "All runs: llama.cpp b11770 (39da130f), coordinator = ASUS ROG Zephyrus G14 GA403WR (RTX 5070 Ti Laptop "
        "12 GiB, CUDA 13.4 build, driver 591.84), Windows 11. Peers named `loopback-*` are a second process on the "
        "same machine; `wsl-ubuntu-*` is a Linux worker in a WSL2 VM on the same machine (separate kernel and "
        "network namespace, real TCP over the Hyper-V virtual switch). The per-run tables involve no second physical "
        "machine. In the lifecycle table, `725198fe` and `865929b9` are the first G14 + M4 MacBook Air runs over "
        "campus Wi-Fi (RPC0 is the Mac); their raw evidence, with decode speeds, is in `results/pair/`.",
        "",
        "Measurement conditions: files labeled `final-*` were measured with the machine otherwise idle. Earlier "
        "files overlapped with background build, test and review work on the same laptop and are slower and noisier "
        "(for example 0.5B local decode 183 tok/s under load vs 527 tok/s idle); compare like with like.",
        "",
        "## Deployments",
        "",
        "State is the deployment state when the script finished measuring. Runs saved with `--keep` were then "
        "ended on purpose by a failure-path test; their final outcome is in the lifecycle section below.",
        "",
        "| evidence | model | strategy | state when measured | observed placement (llama.cpp load log) | peers |"
        " load s | peer work verified |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "## Warm benchmarks (median [min-max]; 1 warmup + N repetitions, concurrency 1)",
        "",
        "TTFT is gateway-measured request-to-first-output. Decode and prompt rates are llama.cpp `timings` "
        "(real token timing; `predicted_per_second` excludes the first token).",
        "",
        "| evidence | model | prompt | prompt cache | TTFT ms | decode tok/s | prompt tok/s | n | failures |",
        "|---|---|---|---|---|---|---|---|---|",
        *bench_rows,
        "",
        "## Lifecycle and failure-path outcomes",
        "",
        f"From `results/{lifecycle_files[-1].name}` (exported from the host's own deployment records by "
        "`scripts/export_lifecycle_evidence.py`). Each row is a deployment that ended in `failed`. Most were on "
        "purpose: gateway hard-killed then restarted (twice: before and after the Windows Job Object change), "
        "friend agent + worker hard-killed, friend ran `hypercompute leave`, friend ran `hypercompute pause`, and a "
        "dashboard run started from a plan whose friend had paused in the meantime. Two are from the G14 + M4 Air "
        "session: `725198fe` (the Mac dropped off mid-request) and `865929b9` (the gateway was stopped after the "
        "last chat; the next start found llama-server gone)."
        if lifecycle_files else "No lifecycle export yet.",
        "",
        "| deployment | model | devices | error | cleanup |",
        "|---|---|---|---|---|",
        *lifecycle_rows,
        "",
        *_concurrency_section(),
    ]
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote docs/RESULTS.md ({len(rows)} deployments, {len(bench_rows)} benchmark rows)")


if __name__ == "__main__":
    main()
